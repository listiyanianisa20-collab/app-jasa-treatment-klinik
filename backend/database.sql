-- Validasi dan pengelolaan booking.
create or replace function public._validasi_slot_booking(
  tanggal_input date,
  jam_input time,
  booking_dikecualikan bigint default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  jam_mulai constant integer := 9;
  jam_selesai constant integer := 20;
  kapasitas_slot constant integer := 2;
  zona_waktu constant text := 'Asia/Jakarta';
  jumlah_booking integer;
begin
  if tanggal_input is null or jam_input is null then
    raise exception 'Tanggal dan jam booking wajib dipilih.';
  end if;
  if extract(isodow from tanggal_input) = 7 then
    raise exception 'Booking tidak tersedia pada hari Minggu.';
  end if;
  if extract(hour from jam_input) < jam_mulai
    or extract(hour from jam_input) >= jam_selesai
    or extract(minute from jam_input) <> 0
    or extract(second from jam_input) <> 0 then
    raise exception 'Jam booking harus pada slot 09:00 sampai 19:00.';
  end if;
  if (tanggal_input + jam_input) <= (now() at time zone zona_waktu) then
    raise exception 'Tanggal dan jam booking tidak boleh sudah lewat.';
  end if;

  perform pg_advisory_xact_lock(
    hashtext('booking:' || tanggal_input::text),
    hashtext(to_char(jam_input, 'HH24:MI'))
  );

  select count(*) into jumlah_booking
  from public.booking b
  where b.tanggal = tanggal_input
    and b.jam = jam_input
    and b.status = 'Dijadwalkan'
    and (booking_dikecualikan is null or b.id_booking <> booking_dikecualikan);

  if jumlah_booking >= kapasitas_slot then
    raise exception 'Slot % pada tanggal % sudah penuh.',
      to_char(jam_input, 'HH24:MI'), to_char(tanggal_input, 'DD Mon YYYY');
  end if;
end;
$$;

create or replace function public.buat_booking(data_booking jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  id_pelanggan_input bigint;
  id_item_input bigint;
  tanggal_input date;
  jam_input time;
  jenis_item text;
  booking_baru public.booking%rowtype;
begin
  id_pelanggan_input := nullif(data_booking->>'id_pelanggan', '')::bigint;
  id_item_input := nullif(data_booking->>'id_item', '')::bigint;
  tanggal_input := nullif(data_booking->>'tanggal', '')::date;
  jam_input := nullif(data_booking->>'jam', '')::time;

  if id_pelanggan_input is null then
    raise exception 'Pelanggan wajib dipilih.';
  end if;
  if not exists (select 1 from public.pelanggan p where p.id_pelanggan = id_pelanggan_input) then
    raise exception 'Pelanggan tidak ditemukan.';
  end if;
  if id_item_input is null then
    raise exception 'Jasa treatment wajib dipilih.';
  end if;
  select i.jenis into jenis_item from public.item i where i.id_item = id_item_input;
  if not found then
    raise exception 'Jasa treatment tidak ditemukan.';
  end if;
  if jenis_item <> 'Jasa Treatment' then
    raise exception 'Booking hanya dapat dibuat untuk jasa treatment.';
  end if;

  perform public._validasi_slot_booking(tanggal_input, jam_input);

  insert into public.booking (id_pelanggan, id_item, tanggal, jam, catatan)
  values (id_pelanggan_input, id_item_input, tanggal_input, jam_input, coalesce(data_booking->>'catatan', ''))
  returning * into booking_baru;

  return jsonb_build_object(
    'id_booking', booking_baru.id_booking,
    'id_pelanggan', booking_baru.id_pelanggan,
    'id_item', booking_baru.id_item,
    'tanggal', booking_baru.tanggal,
    'jam', booking_baru.jam,
    'status', booking_baru.status
  );
end;
$$;

create or replace function public.ubah_jadwal_booking(
  id_booking_input bigint,
  tanggal_baru date,
  jam_baru time
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  booking_terpilih public.booking%rowtype;
begin
  select * into booking_terpilih
  from public.booking
  where id_booking = id_booking_input
  for update;

  if not found then
    raise exception 'Booking tidak ditemukan.';
  end if;
  if booking_terpilih.status <> 'Dijadwalkan' then
    raise exception 'Hanya booking berstatus Dijadwalkan yang dapat diubah jadwalnya.';
  end if;

  perform public._validasi_slot_booking(tanggal_baru, jam_baru, id_booking_input);
  update public.booking
  set tanggal = tanggal_baru, jam = jam_baru
  where id_booking = id_booking_input;

  return jsonb_build_object(
    'id_booking', id_booking_input,
    'tanggal', tanggal_baru,
    'jam', jam_baru,
    'status', booking_terpilih.status
  );
end;
$$;

create or replace function public.ubah_status_booking(
  id_booking_input bigint,
  status_baru text,
  id_penjualan_input bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  booking_terpilih public.booking%rowtype;
begin
  select * into booking_terpilih
  from public.booking
  where id_booking = id_booking_input
  for update;

  if not found then
    raise exception 'Booking tidak ditemukan.';
  end if;
  if booking_terpilih.status <> 'Dijadwalkan' then
    raise exception 'Status booking yang sudah diproses tidak dapat diubah lagi.';
  end if;
  if status_baru is null or status_baru not in ('Selesai', 'Batal', 'Tidak Hadir') then
    raise exception 'Status baru harus Selesai, Batal, atau Tidak Hadir.';
  end if;

  if status_baru = 'Selesai' then
    if id_penjualan_input is null then
      raise exception 'Transaksi penjualan wajib disertakan untuk menyelesaikan booking.';
    end if;
    if not exists (
      select 1
      from public.penjualan p
      join public.detail_penjualan d on d.id_penjualan = p.id_penjualan
      where p.id_penjualan = id_penjualan_input
        and p.id_pelanggan = booking_terpilih.id_pelanggan
        and d.id_item = booking_terpilih.id_item
    ) then
      raise exception 'Transaksi tidak cocok dengan pelanggan dan jasa pada booking.';
    end if;
  elsif id_penjualan_input is not null then
    raise exception 'Nomor transaksi hanya dapat diisi saat booking berstatus Selesai.';
  end if;

  update public.booking
  set status = status_baru,
      id_penjualan = id_penjualan_input
  where id_booking = id_booking_input;

  return jsonb_build_object(
    'id_booking', id_booking_input,
    'status', status_baru,
    'id_penjualan', id_penjualan_input
  );
end;
$$;

-- Pembuatan transaksi dan pembayaran cicilan.
-- Membuat header, detail, total, dan mutasi stok dalam satu transaksi database.
create or replace function buat_penjualan(data_penjualan jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  ambang_diskon numeric(14, 2) := 500000;
  persentase_diskon numeric(5, 2) := 15;
  transaksi_id bigint;
  baris jsonb;
  item_terpilih item%rowtype;
  kuantitas integer;
  subtotal_transaksi numeric(14, 2) := 0;
  subtotal_produk numeric(14, 2) := 0;
  diskon_persen_terhitung numeric(5, 2) := 0;
  diskon_nominal_terhitung numeric(14, 2) := 0;
  total_bersih numeric(14, 2) := 0;
  nilai_baris numeric(14, 2);
  daftar_item jsonb;
  tenor_cicilan integer;
  cicilan_ke integer;
  nominal_cicilan numeric(14, 2);
  tanggal_jatuh_tempo date;
  tanggal_transaksi date;
  jadwal jsonb := '[]'::jsonb;
begin
  if coalesce(jsonb_typeof(data_penjualan->'items'), 'null') <> 'array' then
    raise exception 'Daftar item transaksi tidak valid.';
  end if;
  if jsonb_array_length(data_penjualan->'items') = 0 then
    raise exception 'Tambahkan minimal satu item pada transaksi.';
  end if;

  tanggal_transaksi := coalesce(
    nullif(data_penjualan->>'tanggal', '')::date,
    (now() at time zone 'Asia/Jakarta')::date
  );
  if tanggal_transaksi > (now() at time zone 'Asia/Jakarta')::date then
    raise exception 'Tanggal transaksi tidak boleh setelah hari ini.';
  end if;

  insert into penjualan (id_pelanggan, tanggal, metode_pembayaran, status_pembayaran)
  values (
    (data_penjualan->>'id_pelanggan')::bigint,
    tanggal_transaksi,
    data_penjualan->>'metode_pembayaran',
    case when data_penjualan->>'metode_pembayaran' = 'Kredit' then 'Belum Lunas'
      else 'Lunas' end
  )
  returning id_penjualan into transaksi_id;

  for baris in select value from jsonb_array_elements(data_penjualan->'items')
  loop
    kuantitas := (baris->>'jumlah')::integer;
    if kuantitas <= 0 then
      raise exception 'Jumlah item harus lebih dari nol.';
    end if;

    select * into item_terpilih
    from item
    where id_item = (baris->>'id_item')::bigint
    for update;

    if not found then
      raise exception 'Item tidak ditemukan.';
    end if;

    if item_terpilih.jenis = 'Produk' then
      update item
      set stok = stok - kuantitas
      where id_item = item_terpilih.id_item and stok >= kuantitas;
      if not found then
        raise exception 'Stok % tidak mencukupi.', item_terpilih.nama_item;
      end if;
    end if;

    nilai_baris := item_terpilih.harga_jual * kuantitas;
    insert into detail_penjualan (id_penjualan, id_item, jumlah, harga_satuan, subtotal, harga_pokok_satuan)
    values (
      transaksi_id,
      item_terpilih.id_item,
      kuantitas,
      item_terpilih.harga_jual,
      nilai_baris,
      case when item_terpilih.jenis = 'Produk' then item_terpilih.harga_pokok else 0 end
    );
    subtotal_transaksi := subtotal_transaksi + nilai_baris;
    if item_terpilih.jenis = 'Produk' then
      subtotal_produk := subtotal_produk + nilai_baris;
    end if;
  end loop;

  if subtotal_produk > ambang_diskon then
    diskon_persen_terhitung := persentase_diskon;
    diskon_nominal_terhitung := round(subtotal_produk * persentase_diskon / 100, 2);
  end if;
  total_bersih := subtotal_transaksi - diskon_nominal_terhitung;

  update penjualan
  set subtotal = subtotal_transaksi,
      diskon_persen = diskon_persen_terhitung,
      diskon_nominal = diskon_nominal_terhitung,
      total = total_bersih
  where id_penjualan = transaksi_id;
  if data_penjualan->>'metode_pembayaran' = 'Kredit' then
    tenor_cicilan := nullif(data_penjualan->>'cicilan_bulan', '')::integer;
    tanggal_jatuh_tempo := nullif(data_penjualan->>'tanggal_jatuh_tempo_pertama', '')::date;
    select tanggal into tanggal_transaksi from penjualan where id_penjualan = transaksi_id;
    if tenor_cicilan is null or tenor_cicilan not in (2, 3, 6, 12) then
      raise exception 'Tenor cicilan harus 2, 3, 6, atau 12 bulan.';
    end if;
    if tanggal_jatuh_tempo is null or tanggal_jatuh_tempo < tanggal_transaksi then
      raise exception 'Tanggal jatuh tempo pertama harus sama atau setelah tanggal transaksi.';
    end if;
    if total_bersih <= 0 then
      raise exception 'Total transaksi kredit harus lebih besar dari nol.';
    end if;

    nominal_cicilan := round(total_bersih / tenor_cicilan, 0);
    for cicilan_ke in 1..tenor_cicilan loop
      jadwal := jadwal || jsonb_build_array(jsonb_build_object(
        'cicilan_ke', cicilan_ke,
        'jatuh_tempo', (tanggal_jatuh_tempo + make_interval(months => cicilan_ke - 1))::date,
        'nominal', case when cicilan_ke = tenor_cicilan
          then total_bersih - nominal_cicilan * (tenor_cicilan - 1)
          else nominal_cicilan
        end,
        'tanggal_bayar', null,
        'metode_bayar', null,
        'status', 'Belum Lunas',
        'catatan', ''
      ));
    end loop;
    update penjualan
    set tenor = tenor_cicilan, jadwal_cicilan = jadwal
    where id_penjualan = transaksi_id;
  end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id_item', d.id_item, 'nama_item', i.nama_item, 'jumlah', d.jumlah,
    'harga_satuan', d.harga_satuan, 'subtotal', d.subtotal
  )), '[]'::jsonb)
  into daftar_item
  from detail_penjualan d join item i on i.id_item = d.id_item
  where d.id_penjualan = transaksi_id;

  return jsonb_build_object(
    'id_penjualan', transaksi_id,
    'subtotal', subtotal_transaksi,
    'subtotal_produk', subtotal_produk,
    'diskon_persen', diskon_persen_terhitung,
    'diskon_nominal', diskon_nominal_terhitung,
    'total', total_bersih,
    'items', daftar_item
  );
end;
$$;

create or replace function konfirmasi_pembayaran_cicilan(
  id_penjualan_input bigint,
  cicilan_ke_input integer,
  tanggal_bayar_input date,
  metode_bayar_input text,
  catatan_input text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  penjualan_terpilih public.penjualan%rowtype;
  cicilan_terpilih jsonb;
  jadwal_baru jsonb;
  cicilan_berikutnya integer;
begin
  select * into penjualan_terpilih
  from public.penjualan
  where id_penjualan = id_penjualan_input
  for update;

  if not found then
    raise exception 'Transaksi piutang tidak ditemukan.';
  end if;
  select value into cicilan_terpilih
  from jsonb_array_elements(penjualan_terpilih.jadwal_cicilan) as schedule(value)
  where (value->>'cicilan_ke')::integer = cicilan_ke_input;

  if not found then
    raise exception 'Cicilan tidak ditemukan.';
  end if;
  if cicilan_terpilih->>'status' = 'Lunas' then
    raise exception 'Cicilan ini sudah lunas.';
  end if;
  if tanggal_bayar_input is null then
    raise exception 'Tanggal pembayaran wajib diisi.';
  end if;
  if metode_bayar_input not in ('Tunai', 'Transfer') then
    raise exception 'Metode pembayaran harus Tunai atau Transfer.';
  end if;

  select min((value->>'cicilan_ke')::integer) into cicilan_berikutnya
  from jsonb_array_elements(penjualan_terpilih.jadwal_cicilan) as schedule(value)
  where value->>'status' <> 'Lunas';
  if cicilan_ke_input <> cicilan_berikutnya then
    raise exception 'Pembayaran cicilan harus berurutan.';
  end if;

  select coalesce(jsonb_agg(
    case when (value->>'cicilan_ke')::integer = cicilan_ke_input then
      value || jsonb_build_object(
        'tanggal_bayar', tanggal_bayar_input,
        'metode_bayar', metode_bayar_input,
        'catatan', coalesce(catatan_input, ''),
        'status', 'Lunas'
      )
    else value end
    order by ordinal
  ), '[]'::jsonb)
  into jadwal_baru
  from jsonb_array_elements(penjualan_terpilih.jadwal_cicilan) with ordinality as schedule(value, ordinal);

  update public.penjualan p
  set jadwal_cicilan = jadwal_baru,
      status_pembayaran = case when not exists (
        select 1 from jsonb_array_elements(jadwal_baru) as schedule(value)
        where value->>'status' <> 'Lunas'
      ) then 'Lunas' else 'Belum Lunas' end
  where p.id_penjualan = id_penjualan_input;

  return cicilan_terpilih || jsonb_build_object(
    'tanggal_bayar', tanggal_bayar_input,
    'metode_bayar', metode_bayar_input,
    'catatan', coalesce(catatan_input, ''),
    'status', 'Lunas'
  );
end;
$$;

-- 4. View
-- Satu baris laporan mewakili satu item pada detail transaksi.
create view view_laporan_penjualan with (security_invoker = true) as
select
  p.tanggal as tanggal,
  p.id_penjualan,
  pl.nama as nama_pelanggan,
  i.id_item,
  i.nama_item,
  i.jenis,
  d.jumlah,
  d.harga_satuan,
  d.subtotal,
  p.metode_pembayaran,
  p.status_pembayaran
from penjualan p
join pelanggan pl on pl.id_pelanggan = p.id_pelanggan
join detail_penjualan d on d.id_penjualan = p.id_penjualan
join item i on i.id_item = d.id_item;

create view view_diskon_penjualan with (security_invoker = true) as
select
  p.tanggal,
  p.id_penjualan,
  p.id_pelanggan,
  pl.nama as nama_pelanggan,
  p.subtotal,
  coalesce(produk.subtotal_produk, 0)::numeric(14, 2) as subtotal_produk,
  p.diskon_persen,
  p.diskon_nominal,
  p.total
from penjualan p
join pelanggan pl on pl.id_pelanggan = p.id_pelanggan
left join lateral (
  select sum(d.subtotal)::numeric(14, 2) as subtotal_produk
  from detail_penjualan d
  join item i on i.id_item = d.id_item
  where d.id_penjualan = p.id_penjualan and i.jenis = 'Produk'
) produk on true;

create view view_booking with (security_invoker = true) as
select
  b.id_booking,
  b.id_pelanggan,
  b.id_item,
  pl.nama as nama_pelanggan,
  pl.no_hp,
  pl.alamat,
  i.nama_item,
  i.harga_jual,
  b.tanggal,
  b.jam,
  b.status,
  b.catatan,
  b.id_penjualan,
  b.dibuat_pada
from public.booking b
join public.pelanggan pl on pl.id_pelanggan = b.id_pelanggan
join public.item i on i.id_item = b.id_item;

-- Jurnal otomatis dari transaksi penjualan dan HPP.
create or replace view view_jurnal_umum with (security_invoker = true) as
with debit_penjualan as (
  select
    p.tanggal,
    p.id_penjualan,
    case p.metode_pembayaran
      when 'Kredit' then 'Piutang Usaha'
      when 'Transfer' then 'Bank'
      else 'Kas'
    end as akun,
    p.total as nilai
  from penjualan p
), pendapatan as (
  select
    p.tanggal,
    p.id_penjualan,
    case i.jenis
      when 'Produk' then 'Pendapatan Penjualan Produk'
      else 'Pendapatan Jasa Treatment'
    end as akun,
    sum(d.subtotal) as nilai
  from penjualan p
  join detail_penjualan d on d.id_penjualan = p.id_penjualan
  join item i on i.id_item = d.id_item
  group by p.tanggal, p.id_penjualan, i.jenis
), hpp_produk as (
  select
    p.tanggal,
    p.id_penjualan,
    sum(d.jumlah * d.harga_pokok_satuan) as nilai
  from penjualan p
  join detail_penjualan d on d.id_penjualan = p.id_penjualan
  join item i on i.id_item = d.id_item
  where i.jenis = 'Produk'
  group by p.tanggal, p.id_penjualan
), jurnal_asli as (
  select
    tanggal, id_penjualan, 1::integer as urutan,
    case when akun = 'Piutang Usaha' then 'Penjualan kredit'
      else 'Penerimaan penjualan tunai/transfer' end::text as keterangan,
    akun, nilai as debit, 0::numeric(14, 2) as kredit
  from debit_penjualan
  union all
  select tanggal, id_penjualan,
    (10 + row_number() over (partition by id_penjualan order by akun))::integer,
    'Pengakuan pendapatan'::text, akun, 0::numeric(14, 2), nilai
  from pendapatan
  union all
  select
    p.tanggal, p.id_penjualan, 2::integer,
    'Diskon produk 15% (belanja produk di atas Rp 500.000)'::text,
    'Diskon Penjualan'::text, p.diskon_nominal, 0::numeric(14, 2)
  from penjualan p
  where p.diskon_nominal > 0
  union all
  select tanggal, id_penjualan, 20::integer, 'Pengakuan HPP produk'::text,
    'Beban Pokok Penjualan'::text, nilai, 0::numeric(14, 2)
  from hpp_produk
  where nilai > 0
  union all
  select tanggal, id_penjualan, 21::integer, 'Pengurangan persediaan produk'::text,
    'Persediaan Produk'::text, 0::numeric(14, 2), nilai
  from hpp_produk
  where nilai > 0
)
select tanggal, id_penjualan, urutan, keterangan, akun, debit, kredit from jurnal_asli;

create view view_jurnal_pelunasan with (security_invoker = true) as
select
  (c.value->>'tanggal_bayar')::date as tanggal,
  p.id_penjualan,
  1::integer as urutan,
  coalesce(nullif(c.value->>'catatan', ''), 'Pembayaran cicilan ke-' || (c.value->>'cicilan_ke'))::text as keterangan,
  case c.value->>'metode_bayar' when 'Transfer' then 'Bank' else 'Kas' end as akun,
  (c.value->>'nominal')::numeric(14, 2) as debit,
  0::numeric(14, 2) as kredit
from penjualan p
cross join lateral jsonb_array_elements(p.jadwal_cicilan) as c(value)
where c.value->>'status' = 'Lunas'
union all
select
  (c.value->>'tanggal_bayar')::date as tanggal,
  p.id_penjualan,
  2::integer as urutan,
  coalesce(nullif(c.value->>'catatan', ''), 'Pelunasan piutang cicilan ke-' || (c.value->>'cicilan_ke'))::text,
  'Piutang Usaha'::text,
  0::numeric(14, 2),
  (c.value->>'nominal')::numeric(14, 2)
from penjualan p
cross join lateral jsonb_array_elements(p.jadwal_cicilan) as c(value)
where c.value->>'status' = 'Lunas';

create view view_laporan_pelunasan with (security_invoker = true) as
select
  (c.value->>'tanggal_bayar')::date as tanggal,
  p.id_penjualan,
  p.id_pelanggan,
  pl.nama as nama_pelanggan,
  (c.value->>'cicilan_ke')::integer as cicilan_ke,
  c.value->>'metode_bayar' as metode_pembayaran,
  coalesce(nullif(c.value->>'catatan', ''), 'Pembayaran cicilan') as keterangan,
  (c.value->>'nominal')::numeric(14, 2) as nominal
from penjualan p
join pelanggan pl on pl.id_pelanggan = p.id_pelanggan
cross join lateral jsonb_array_elements(p.jadwal_cicilan) as c(value)
where c.value->>'status' = 'Lunas';

create view view_piutang with (security_invoker = true) as
select
  p.id_penjualan,
  p.id_pelanggan,
  p.tanggal,
  p.metode_pembayaran,
  p.status_pembayaran,
  p.total,
  p.tenor,
  coalesce(sum(case when c.value->>'status' = 'Lunas' then (c.value->>'nominal')::numeric else 0 end), 0)::numeric(14, 2) as total_dibayar,
  coalesce(sum(case when c.value->>'status' <> 'Lunas' then (c.value->>'nominal')::numeric else 0 end), 0)::numeric(14, 2) as sisa_pembayaran,
  count(c.value)::integer as jumlah_cicilan,
  count(*) filter (where c.value->>'status' <> 'Lunas')::integer as sisa_tenor,
  min((c.value->>'jatuh_tempo')::date) filter (where c.value->>'status' <> 'Lunas') as jatuh_tempo_berikutnya
from penjualan p
left join lateral jsonb_array_elements(p.jadwal_cicilan) as c(value) on true
where p.metode_pembayaran = 'Kredit'
group by p.id_penjualan;

create or replace view view_laba_rugi with (security_invoker = true) as
with per_penjualan as (
  select
    p.tanggal,
    p.id_penjualan,
    sum(d.subtotal)::numeric(14, 2) as pendapatan,
    p.diskon_nominal::numeric(14, 2) as diskon_penjualan,
    sum(case when i.jenis = 'Produk' then d.jumlah * d.harga_pokok_satuan else 0 end)::numeric(14, 2) as hpp
  from penjualan p
  join detail_penjualan d on d.id_penjualan = p.id_penjualan
  join item i on i.id_item = d.id_item
  group by p.tanggal, p.id_penjualan, p.diskon_nominal
)
select tanggal, id_penjualan, 1 as urutan, 'Pendapatan'::text as akun, pendapatan as nilai from per_penjualan
union all
select tanggal, id_penjualan, 2, 'Diskon Penjualan'::text, diskon_penjualan from per_penjualan
union all
select tanggal, id_penjualan, 3, 'Beban Pokok Penjualan'::text, hpp from per_penjualan
union all
select tanggal, id_penjualan, 4, 'Laba Kotor'::text, pendapatan - diskon_penjualan - hpp from per_penjualan;

create view view_buku_besar with (security_invoker = true) as
select tanggal, id_penjualan, urutan, keterangan, akun, debit, kredit from view_jurnal_umum
union all
select tanggal, id_penjualan, urutan, keterangan, akun, debit, kredit from view_jurnal_pelunasan;

-- 5. Keamanan (RLS & grant)
-- Transaksi bersifat final: tulis hanya lewat fungsi database, bukan lewat akses tabel langsung.
-- Akses data hanya untuk pengguna admin yang sudah terautentikasi.
do $$
declare
  table_name text;
  policy_row record;
begin
  foreach table_name in array array['pelanggan', 'item', 'penjualan', 'detail_penjualan', 'booking']
  loop
    execute format('alter table public.%I enable row level security', table_name);

    for policy_row in
      select policyname
      from pg_policies
      where schemaname = 'public'
        and tablename = table_name
        and policyname like 'demo_anon_%'
    loop
      execute format('drop policy %I on public.%I', policy_row.policyname, table_name);
    end loop;

    for policy_row in
      select * from (values
        ('select', 'SELECT', 'using (true)'),
        ('insert', 'INSERT', 'with check (true)'),
        ('update', 'UPDATE', 'using (true) with check (true)'),
        ('delete', 'DELETE', 'using (true)')
      ) as authenticated_policies(operation, operation_sql, clause)
    loop
      execute format('drop policy if exists authenticated_%1$s on public.%2$I', policy_row.operation, table_name);
      if table_name in ('pelanggan', 'item') or policy_row.operation = 'select' then
        execute format(
          'create policy authenticated_%1$s on public.%2$I for %3$s to authenticated %4$s',
          policy_row.operation,
          table_name,
          policy_row.operation_sql,
          policy_row.clause
        );
      end if;
    end loop;
  end loop;
end;
$$;

