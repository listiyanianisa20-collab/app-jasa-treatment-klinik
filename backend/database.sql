-- Skema Sistem Informasi Akuntansi Penjualan Lsty Klinik

-- 1. Tabel
-- Tabel pelanggan.
create table if not exists pelanggan (
  id_pelanggan bigint generated by default as identity primary key,
  nama text not null check (length(trim(nama)) > 0),
  no_hp text not null default 'Belum diisi' check (length(trim(no_hp)) > 0),
  alamat text not null default '',
  tanggal_daftar date not null default current_date
);

-- Tabel katalog item.
create table if not exists item (
  id_item bigint generated by default as identity primary key,
  nama_item text not null check (length(trim(nama_item)) > 0),
  jenis text not null check (jenis in ('Produk', 'Jasa Treatment')),
  harga_jual numeric(14, 2) not null check (harga_jual >= 0),
  harga_pokok numeric(14, 2) not null default 0 check (harga_pokok >= 0),
  stok integer,
  constraint item_stok_jenis_check check (
    (jenis = 'Produk' and stok is not null and stok >= 0)
    or (jenis = 'Jasa Treatment' and stok is null and harga_pokok = 0)
  )
);

-- Tabel penjualan.
create table if not exists penjualan (
  id_penjualan bigint generated by default as identity primary key,
  id_pelanggan bigint not null references pelanggan(id_pelanggan),
  tanggal date not null default current_date,
  metode_pembayaran text not null check (metode_pembayaran in ('Tunai', 'Transfer', 'Kredit')),
  status_pembayaran text not null default 'Lunas' check (status_pembayaran in ('Lunas', 'Belum Lunas')),
  total numeric(14, 2) not null default 0 check (total >= 0),
  subtotal numeric(14, 2) not null default 0 check (subtotal >= 0),
  diskon_persen numeric(5, 2) not null default 0,
  diskon_nominal numeric(14, 2) not null default 0 check (diskon_nominal >= 0 and diskon_nominal <= subtotal),
  tenor integer,
  jadwal_cicilan jsonb not null default '[]'::jsonb
);

-- Tabel detail penjualan dengan snapshot HPP.
create table if not exists detail_penjualan (
  id_detail bigint generated by default as identity primary key,
  id_penjualan bigint not null references penjualan(id_penjualan) on delete cascade,
  id_item bigint not null references item(id_item),
  jumlah integer not null check (jumlah > 0),
  harga_satuan numeric(14, 2) not null check (harga_satuan >= 0),
  subtotal numeric(14, 2) not null check (subtotal >= 0),
  harga_pokok_satuan numeric(14, 2) not null default 0,
  constraint detail_penjualan_harga_pokok_satuan_check check (harga_pokok_satuan >= 0)
);

-- Tabel booking.
create table if not exists public.booking (
  id_booking bigint generated by default as identity primary key,
  id_pelanggan bigint not null references public.pelanggan(id_pelanggan),
  id_item bigint not null references public.item(id_item),
  tanggal date not null,
  jam time not null,
  status text not null default 'Dijadwalkan'
    check (status in ('Dijadwalkan', 'Selesai', 'Batal', 'Tidak Hadir')),
  catatan text not null default '',
  id_penjualan bigint references public.penjualan(id_penjualan),
  dibuat_pada timestamptz not null default now()
);

-- Hapus view lama sebelum menghapus kolom yang tidak lagi dipakai.
drop view if exists public.view_buku_besar;
drop view if exists public.view_laba_rugi;
drop view if exists public.view_piutang;
drop view if exists public.view_laporan_pelunasan;
drop view if exists public.view_jurnal_pelunasan;
drop view if exists public.view_jurnal_umum;
drop view if exists public.view_diskon_penjualan;
drop view if exists public.view_laporan_penjualan;
drop view if exists public.view_booking;
alter table public.penjualan drop constraint if exists penjualan_status_transaksi_check;
alter table public.penjualan drop column if exists status_transaksi, drop column if exists tanggal_void, drop column if exists alasan_void;
alter table public.item drop column if exists foto_url, drop column if exists foto;

-- Lengkapi snapshot dan nilai transaksi lama yang belum terisi.
update public.penjualan
set subtotal = coalesce(subtotal, total),
    diskon_persen = coalesce(diskon_persen, 0),
    diskon_nominal = coalesce(diskon_nominal, 0)
where subtotal is null or diskon_persen is null or diskon_nominal is null;
update public.detail_penjualan d
set harga_pokok_satuan = case when i.jenis = 'Produk' then i.harga_pokok else 0 end
from public.item i
where i.id_item = d.id_item and d.harga_pokok_satuan is null;

-- 2. Indeks
create index if not exists booking_tanggal_jam_idx on public.booking(tanggal, jam);
create index if not exists penjualan_tanggal_idx on penjualan(tanggal);
create index if not exists penjualan_pelanggan_idx on penjualan(id_pelanggan);
create index if not exists detail_penjualan_penjualan_idx on detail_penjualan(id_penjualan);
create index if not exists detail_penjualan_item_idx on detail_penjualan(id_item);

